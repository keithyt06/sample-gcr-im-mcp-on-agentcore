import { Aspects, Stack, Validations, type IAspect } from 'aws-cdk-lib';
import { CfnPolicy } from 'aws-cdk-lib/aws-iam';
import { CfnRoute } from 'aws-cdk-lib/aws-apigatewayv2';
import { CfnDistribution } from 'aws-cdk-lib/aws-cloudfront';
import { CfnFunction } from 'aws-cdk-lib/aws-lambda';
import { CfnSecret } from 'aws-cdk-lib/aws-secretsmanager';
import type { IConstruct } from 'constructs';
// Same flattening cdk-nag uses to build IAM5 finding ids.
import { flattenCfnReference } from 'cdk-nag/lib/utils/flatten-cfn-reference.js';

/** Resource: "*" is allowed ONLY for these actions (no resource-level permissions). Mirrors test/infra/iam.test.ts. */
export const STAR_RESOURCE_ACTIONS = new Set(['ecr:GetAuthorizationToken', 'secretsmanager:ListSecrets']);

interface Stmt {
  Effect: string;
  Action: string | string[];
  Resource: unknown;
}
const arr = <T>(x: T | T[]): T[] => (Array.isArray(x) ? x : [x]);

/** Wildcard resource patterns that are part of the design, with the reason. Matched on the flattened finding. */
function wildcardReason(resource: string, actions: string[], slug: string): string | undefined {
  if (resource === '*' && actions.every((a) => STAR_RESOURCE_ACTIONS.has(a)))
    return `${actions.join(', ')} has no resource-level permissions (documented exception)`;
  if (/^<[A-Za-z0-9]+\.Arn>:\*$/.test(resource) && actions.every((a) => a.startsWith('logs:')))
    return "Log streams inside this function's own log group (stream names are generated by Lambda)";
  if (/^<[A-Za-z0-9]+\.AgentRuntimeArn>\/\*$/.test(resource) && actions.every((a) => a === 'bedrock-agentcore:InvokeAgentRuntime'))
    return 'Endpoints of this stack\'s own runtime (the service-managed DEFAULT endpoint is a sub-resource)';
  if (resource.includes(':log-group:/aws/bedrock-agentcore/runtimes/*'))
    return 'The runtime log group is created by the AgentCore service and named after the runtime id, unknown at synth time';
  if (resource.endsWith(`:secret:${slug}/users/*`))
    return 'Per-user IM credential secrets are created at runtime under this deployment\'s prefix (one secret per user)';
  return undefined;
}

class NagAcks implements IAspect {
  constructor(private readonly slug: string) {}

  visit(node: IConstruct): void {
    const ack = (id: string, reason: string) => Validations.of(node).acknowledge({ id, reason });

    if (node instanceof CfnPolicy) {
      const doc = Stack.of(node).resolve(node.policyDocument) as { Statement?: Stmt[] };
      for (const st of doc.Statement ?? []) {
        if (st.Effect !== 'Allow') continue;
        const actions = arr(st.Action);
        for (const r of arr(st.Resource).map(flattenCfnReference)) {
          if (!r.includes('*')) continue;
          const reason = wildcardReason(r, actions, this.slug);
          if (reason) ack(`AwsSolutions-IAM5[Resource::${r}]`, reason);
        }
      }
    } else if (node instanceof CfnRoute) {
      ack(
        'AwsSolutions-APIG4',
        'Public OAuth 2.1 endpoints (RFC 8414/9728/7591) must be unauthenticated; /mcp verifies the HMAC-signed bearer token in the middleware Lambda (no Cognito in AWS China)',
      );
    } else if (node instanceof CfnFunction) {
      ack('AwsSolutions-L1', 'Node.js 22 is pinned on purpose to match the container base image and the verified China-region runtime list');
    } else if (node instanceof CfnSecret) {
      ack(
        'AwsSolutions-SMG4',
        'Root key rotation is an operator action (put-secret-value invalidates all tokens within 5 minutes); the IM app secret is issued by the IM vendor and cannot be rotated by AWS',
      );
    } else if (node instanceof CfnDistribution) {
      ack('AwsSolutions-CFR1', 'Sample: no geo restriction; users are wherever the IM tenant is');
      ack('AwsSolutions-CFR2', 'WAF is optional (ingress.waf: true); API Gateway throttling always applies');
      ack('AwsSolutions-CFR3', 'Sample: API Gateway access logs already record every request');
      ack('AwsSolutions-CFR4', 'Default CloudFront certificate: edge: cloudfront with a custom domain is out of scope in v1 (R9), so the TLS policy cannot be raised');
    }
  }
}

/** Register the documented cdk-nag acknowledgements on the stack. */
export function applyNag(stack: Stack, slug: string): void {
  Aspects.of(stack).add(new NagAcks(slug));
}
